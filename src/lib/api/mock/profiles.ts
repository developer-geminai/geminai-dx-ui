import type { AgentMode, Confidence, OrgProfile } from "../types";

export interface QuestionTemplate {
  kind: "question" | "exception" | "approval";
  stepIndex: number;
  context: string;
  text: string;
  options: string[];
  data: [string, string][];
  rule?: { condition: string; action: string };
}

export interface AgentTemplate {
  id: string;
  name: string;
  area: string;
  summary: string;
  mode: AgentMode;
  pausedFrom?: AgentMode;
  pauseReason?: string;
  version: string;
  flow: [string, string][]; // [label, system]
  systems: [string, "read" | "read_write"][];
  granted: string[];
  denied: string[];
  schedule: string;
  owner: string;
  /** Runs per working day when running. */
  dailyRuns: number;
  /** Share of runs that need no human. */
  autonomy: number;
  /** Minutes a person used to spend per case (drives hours saved). */
  manualMinutes: number;
  avgRunSec: number;
  triggers: string[];
  caseSummaries: string[];
  stepActions: [string, string, string][]; // per flow step: [action, decision, reason]
  stepData: [string, string][][]; // masked data per flow step
  questions: QuestionTemplate[];
  shadowCases?: [string, string, string][]; // [case, agent would do, team did]
  opportunityRank?: number;
}

export interface OpportunityTemplate {
  rank: number;
  workflow: string;
  shortName: string;
  department: string;
  description: string;
  sequence: string[];
  weeklyHours: number;
  frequencyPerWeek: number;
  avgDurationMin: number;
  copyPasteRate: number;
  confidence: Confidence;
  timeToLive: string;
  agentId?: string;
  whatWeNeed: string[];
  whatWeDeliver: string[];
}

